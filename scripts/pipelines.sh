#!/bin/sh
# The test and example pipelines as one multi-call binary,
# build/test-pipelines, with build/<name> a link to it for each pipeline
# named (all of them when none is). The binary runs the pipeline its name
# says, `basename "$0"`, as that pipeline's own binary would: argv keeps the
# link's path, so describe, locate, the processes' command lines (pgrep)
# and a copy under the same name (tests/config.sh) are those of its own
# binary. The code they share (morca, dista, postgres...) compiles once, not
# once per pipeline (#447); census's scripts/multicall.sh does the same for
# its image.
#
# A pipeline that used to be built once per -D value is in it once per
# value: GRANTEE and VDAILY_* are comptime parameters of a function in its
# file (`run[...]`), which the table below instantiates for each name.
#
#   scripts/pipelines.sh --as NAME PROGRAM [KEY=VALUE...]
#
# links build/NAME too, running PROGRAM with the source the KEYs give
# (MORCA_SOURCE, MORCA_COMMIT, MORCA_DIRTY), which a test used to give with
# -D. They are written to build/NAME.defines, which the binary reads when
# it runs as NAME and sets in its environment before PROGRAM starts, where
# morca._internal.source reads a binary's source when it has no defines.
# MORCA_DIRTY is read from the environment only in a build with
# -D MORCA_TEST_SOURCE_ENV=1, this one; see that module.
#
# A pipeline built with other flags (toy-g1's -g1) is still a binary of its
# own. The build is one mojo-build.sh call, so an unchanged one is a copy.
#
# Usage: scripts/pipelines.sh [NAME...]
#        scripts/pipelines.sh --as NAME PROGRAM [KEY=VALUE...]
set -eu
cd "$(dirname "$0")/.."

# name:source[:call]. Each source is imported as a module, by its file's
# name, so no two files may share one; call is the function the name runs
# (main when not given). No spaces: the lines are split on them.
all='toy:examples/toy.mojo
fanout:examples/fanout.mojo
daily:examples/daily.mojo
chaos_pipeline:tests/chaos_pipeline.mojo
defer:tests/defer_pipeline.mojo
hourly:tests/hourly.mojo
six-hourly:tests/six_hourly.mojo
stop:tests/stop_pipeline.mojo
longpoll:tests/outdated_pipeline.mojo
ds-first:tests/datasets/first.mojo
ds-second:tests/datasets/second.mojo
ds-third:tests/datasets/third.mojo
ds-compacts:tests/datasets/compacts.mojo
ds-replacer:tests/datasets/replacer.mojo
hog:tests/usage/hog.mojo
grower:tests/cgroups/grower.mojo
fillwk:tests/pool/fillwk.mojo
presser:tests/pressure/presser.mojo
wide:tests/grants/grantee.mojo:run["wide"]
narrow:tests/grants/grantee.mojo:run["narrow"]
plain:tests/grants/grantee.mojo:run["plain"]
vdaily-v0:tests/fill_version/vdaily.mojo:run[0,False]
vdaily-other:tests/fill_version/vdaily.mojo:run[0,True]
vdaily-v1:tests/fill_version/vdaily.mojo:run[1,False]'
# The calls' brackets are glob characters.
set -f

name_of() { echo "${1%%:*}"; }
src_of() { r=${1#*:}; echo "${r%%:*}"; }
mod_of() { basename "$(src_of "$1")" .mojo; }
call_of() {
    r=${1#*:}
    case $r in *:*) echo "${r#*:}" ;; *) echo main ;; esac
}
known() {
    for p in $all; do [ "$(name_of "$p")" = "$1" ] && return 0; done
    return 1
}

binary=test-pipelines
gen=build/pipelines-gen
mkdir -p "$gen"
main=$gen/test_pipelines_main.mojo
tmp=$main.tmp.$$
trap 'rm -f "$tmp"' EXIT INT TERM
{
    echo '"""Generated by scripts/pipelines.sh: the pipeline basename(argv[0])'
    echo 'names, or the one its NAME.defines file names, with that file'"'"'s'
    echo 'source in the environment."""'
    echo
    echo 'from std.os import setenv'
    echo 'from std.os.path import exists'
    echo 'from std.sys import argv'
    echo
    mods=""
    for p in $all; do
        m=$(mod_of "$p")
        case " $mods " in *" $m "*) continue ;; esac
        mods="$mods $m"
        echo "import $m"
    done
    echo
    echo
    echo 'def main() raises:'
    echo '    var me = String(argv()[0])'
    echo '    var slash = me.rfind("/")'
    echo '    var name = String(me[byte = slash + 1 :]) if slash >= 0 else me'
    echo '    var defines = String(me, ".defines")'
    echo '    if exists(defines):'
    echo '        with open(defines, "r") as f:'
    echo '            for line in f.read().splitlines():'
    echo '                var eq = line.find("=")'
    echo '                if eq < 0:'
    echo '                    continue'
    echo '                var k = String(line[byte=:eq])'
    echo '                var v = String(line[byte = eq + 1 :])'
    echo '                if k == "program":'
    echo '                    name = v'
    echo '                elif ('
    echo '                    k == "MORCA_SOURCE"'
    echo '                    or k == "MORCA_COMMIT"'
    echo '                    or k == "MORCA_DIRTY"'
    echo '                ):'
    echo '                    _ = setenv(k, v, True)'
    echo '                else:'
    echo '                    raise Error(defines, ": unknown key ", k)'
    kw=if
    names=""
    for p in $all; do
        n=$(name_of "$p")
        names="$names $n"
        echo "    $kw name == \"$n\":"
        echo "        $(mod_of "$p").$(call_of "$p")()"
        kw=elif
    done
    echo '    else:'
    echo "        raise Error(name, \": not a pipeline of this binary; link it as one of:$names\")"
} > "$tmp"
# Only a changed file is replaced, so builds at once see a whole one.
if cmp -s "$tmp" "$main"; then rm -f "$tmp"; else mv -f "$tmp" "$main"; fi

inc=""
for p in $all; do
    d=$(dirname "$(src_of "$p")")
    case " $inc " in *" -I $d "*) ;; *) inc="$inc -I $d" ;; esac
done
# shellcheck disable=SC2086
scripts/mojo-build.sh -D MORCA_TEST_SOURCE_ENV=1 -I src $inc $DEP_INC "$main" -o "build/$binary"

link() {
    # A link made beside it and moved into place: a test running
    # build/<name> never sees it missing.
    ln -sf "$binary" "build/$1.ln.$$"
    mv -f "build/$1.ln.$$" "build/$1"
}

if [ "${1:-}" = --as ]; then
    [ "$#" -ge 3 ] || { echo "usage: pipelines.sh --as NAME PROGRAM [KEY=VALUE...]" >&2; exit 1; }
    as=$2
    prog=$3
    shift 3
    known "$prog" || { echo "pipelines.sh: no pipeline $prog" >&2; exit 1; }
    ! known "$as" || { echo "pipelines.sh: $as is a pipeline's own name" >&2; exit 1; }
    {
        echo "program=$prog"
        for kv in "$@"; do
            case $kv in
            MORCA_SOURCE=* | MORCA_COMMIT=* | MORCA_DIRTY=*) echo "$kv" ;;
            *)
                echo "pipelines.sh: $kv: only MORCA_SOURCE, MORCA_COMMIT and MORCA_DIRTY" >&2
                exit 1
                ;;
            esac
        done
    } > "build/$as.defines.$$"
    mv -f "build/$as.defines.$$" "build/$as.defines"
    link "$as"
    exit 0
fi

[ "$#" -gt 0 ] || set -- $(for p in $all; do name_of "$p"; done)
for n in "$@"; do
    known "$n" || { echo "pipelines.sh: no pipeline $n" >&2; exit 1; }
    rm -f "build/$n.defines"
    link "$n"
done
